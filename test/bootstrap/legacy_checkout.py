#!/usr/bin/env python3
"""Transfer a real v0.5.1 checkout and exercise its diagnostics on an ARM host."""
import argparse
from contextlib import closing
import json
from pathlib import Path
import subprocess
import tempfile

from support import BASELINE_ENGINE_SHA256, BASELINE_RELEASE_IDENTITY, BASELINE_VERSION, require
from release_targets import DARWIN_ARM64, LINUX_ARM64, LINUX_X64, host_target, payload_engine
from test_delivery import HttpsFixture, digest, environment, file_map


def run(argv, cwd, env, *, success=True):
    result = subprocess.run(argv, cwd=cwd, env=env, stdin=subprocess.DEVNULL,
                            capture_output=True, text=True, timeout=60)
    require((result.returncode == 0) == success,
            f"{argv}: {result.returncode}\n{result.stdout}\n{result.stderr}")
    return result


def export_checkout(release, bundle, scratch, env):
    engine = release / "devkit"
    require(host_target() == LINUX_X64 and digest(engine) == BASELINE_ENGINE_SHA256,
            "The legacy checkout must be generated by the released x86-64 engine")
    require(digest(release / "release.json") == BASELINE_RELEASE_IDENTITY, "Unexpected baseline payload")
    checkout = scratch / "legacy"
    created = run([engine, "init", checkout, "--app", "api=rust-api", "--name", "legacy",
                   "--release-root", release, "--offline", "--package-source", "local", "--json"], scratch, env)
    require(json.loads(created.stdout)["result"]["releaseIdentity"] == BASELINE_RELEASE_IDENTITY,
            "Legacy init accepted a different release")
    with (checkout / "apps/api/src/main.rs").open("a") as source:
        source.write("\n// Product-owned change present before the environment upgrade.\n")
    run(["git", "init", "--quiet", "-b", "main"], checkout, env)
    run(["git", "add", "."], checkout, env)
    run(["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
         "commit", "--quiet", "-m", "Create the v0.5.1 checkout"], checkout, env)
    run(["git", "bundle", "create", bundle, "refs/heads/main"], checkout, env)


def verify_checkout(release, bundle, scratch, env):
    target = host_target()
    require(target in (LINUX_ARM64, DARWIN_ARM64), "Legacy diagnostics require an ARM64 host")
    checkout = scratch / "legacy"
    run(["git", "clone", "--quiet", "-b", "main", bundle, checkout], scratch, env)
    manifest = checkout / ".devkit/manifest.json"
    state = json.loads(manifest.read_bytes())
    require((state["version"], state["releaseIdentity"]) == (BASELINE_VERSION, BASELINE_RELEASE_IDENTITY),
            "Transferred checkout has another accepted release")
    engine = payload_engine(release)
    version = json.loads((release / "release.json").read_bytes())["version"]
    local_path = "/path/to/preview" if target == DARWIN_ARM64 else "/path/to/release"
    local_command = f"{local_path}/{engine.name} update . --to {version} --release-root {local_path}"
    npm_command = f"npx @docouno/devkit@{version} update . --to {version}"
    before = file_map(checkout)
    with closing(HttpsFixture(scratch / "tls").start()) as network:
        proxy = f"http://127.0.0.1:{network.proxy_port}"
        env = dict(env, HTTPS_PROXY=proxy, HTTP_PROXY=proxy, SSL_CERT_FILE=str(network.root / "ca.pem"),
                   CURL_CA_BUNDLE=str(network.root / "ca.pem"), DOCKER_HOST=f"unix://{scratch}/absent.sock")
        for args in (["info"], ["describe"], ["status"], ["sync", "--preview"], ["doctor"],
                     ["run", "info"], ["run", "doctor"]):
            if args[0] == "run":
                output = run([engine, *args], checkout, env, success=False).stderr
            else:
                response = run([engine, *args, "--json"], checkout, env, success=False)
                report = json.loads(response.stdout)
                require(report["ok"] is False, f"{args} admitted a legacy checkout")
                if args == ["doctor"]:
                    check = next(c for c in report["result"]["checks"] if c["id"] == "checkout_state")
                    require(check["status"] == "fail", f"Doctor accepted the legacy checkout: {check}")
                    output = check["remediation"]
                else:
                    require(report["error"]["code"] == "UNSUPPORTED_HOST_TARGET", str(report))
                    output = report["error"]["message"]
            require(local_command in output and (npm_command in output) == (target == LINUX_ARM64),
                    f"{args} omitted the working upgrade path for {target}: {output}")
            require(file_map(checkout) == before and not (checkout / ".devkit/state").exists()
                    and not (checkout / ".devkit/cache").exists() and not Path(env["DEVKIT_CACHE_DIR"]).exists(),
                    f"{args} mutated the old checkout or its cold cache")
        recovered = run([engine, "recover", ".", "--json"], checkout, env)
        require(json.loads(recovered.stdout)["result"]["recovered"] is False and file_map(checkout) == before,
                "Clean recovery changed the transferred checkout")
        upgrade = [engine, "update", ".", "--to", version, "--release-root", release, "--offline", "--json"]
        run([*upgrade, "--preview"], checkout, env)
        run(["git", "diff", "--exit-code", "HEAD"], checkout, env)
        run(upgrade, checkout, env)
        require(json.loads(manifest.read_bytes())["releaseIdentity"] == digest(release / "release.json"),
                "The local upgrade did not accept the host release")
        run(["git", "diff", "--exit-code", "HEAD", "--", "Makefile", "compose.yaml",
             ".config/wt.toml", "apps/api/src/main.rs"], checkout, env)
        require(not network.connections and not network.requests and not network.errors,
                f"Unexpected release acquisition: {network.connections}, {network.requests}, {network.errors}")
    print(f"PASS v{BASELINE_VERSION} checkout diagnostics, recovery and local upgrade on {target}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("export", "verify"))
    parser.add_argument("--release", required=True, type=Path)
    parser.add_argument("--bundle", required=True, type=Path)
    args = parser.parse_args()
    bundle = args.bundle.resolve()
    with tempfile.TemporaryDirectory(prefix="legacy checkout ", dir=bundle.parent) as directory:
        scratch = Path(directory)
        env = environment(scratch, GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL="/dev/null", GIT_OPTIONAL_LOCKS="0")
        (scratch / "home").mkdir()
        operation = export_checkout if args.operation == "export" else verify_checkout
        operation(args.release.resolve(), bundle, scratch, env)


if __name__ == "__main__":
    main()
